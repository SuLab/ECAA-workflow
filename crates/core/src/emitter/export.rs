/// Re-declare `DEPOSIT-READINESS.json` as a `CreativeWork` in the deposit's
/// RO-Crate `@graph`, linked from the root Dataset via `mentions`.
///
/// The emitter declares this entity at emit time (`crate::ro_crate`, DR-11),
/// but the export's [`prune_rocrate_dangling`] necessarily removes it: the
/// attestation is written at the very END of
/// [`export_depositable_package_with_profile`] and so is genuinely absent from
/// disk when the prune runs. The net effect in every shipped deposit was an
/// attestation with ZERO references in its own provenance graph — while
/// `emitter::bagit` documents the manifest exclusion as safe precisely BECAUSE
/// the file "is surfaced instead as an RO-Crate `@graph` CreativeWork".
///
/// `mentions` (not `hasPart`) is the honest edge: the file is a mutable meta
/// artifact off the sealed payload manifest. The node carries no `sha512`, so
/// the post-seal content-hash recheck is unaffected. Idempotent — returns
/// whether the graph changed.
fn ensure_deposit_readiness_entity(dst: &Path) -> Result<bool> {
    use serde_json::Value;
    let id = crate::deposit_readiness::DEPOSIT_READINESS_FILE;
    let descriptor = dst.join("ro-crate-metadata.json");
    let Ok(bytes) = std::fs::read(&descriptor) else {
        return Ok(false);
    };
    let Ok(mut doc) = serde_json::from_slice::<Value>(&bytes) else {
        return Ok(false);
    };
    let Some(graph) = doc.get_mut("@graph").and_then(Value::as_array_mut) else {
        return Ok(false);
    };

    let mut changed = false;
    if !graph
        .iter()
        .any(|e| e.get("@id").and_then(Value::as_str) == Some(id))
    {
        graph.push(serde_json::json!({
            "@id": id,
            "@type": "CreativeWork",
            "name": "Deposit-readiness attestation",
            "description": "Self-validation verdict written by `ecaa-workflow export`: RO-Crate re-verify + BagIt checksum integrity (Layer 1) and, for the re-executable profile, re-execution equivalence (Layer 2). Mutable meta file — excluded from the payload manifest by design.",
            "encodingFormat": "application/json"
        }));
        changed = true;
    }
    // Link it from the root Dataset. `mentions` is created when absent.
    for entry in graph.iter_mut() {
        if entry.get("@id").and_then(Value::as_str) != Some("./") {
            continue;
        }
        let Some(obj) = entry.as_object_mut() else {
            continue;
        };
        let already = obj
            .get("mentions")
            .and_then(Value::as_array)
            .is_some_and(|a| {
                a.iter()
                    .any(|m| m.get("@id").and_then(Value::as_str) == Some(id))
            });
        if already {
            break;
        }
        match obj.get_mut("mentions").and_then(Value::as_array_mut) {
            Some(arr) => arr.push(serde_json::json!({ "@id": id })),
            None => {
                obj.insert(
                    "mentions".to_string(),
                    serde_json::json!([{ "@id": id }]),
                );
            }
        }
        changed = true;
        break;
    }

    if changed {
        let serialized = serde_json::to_vec_pretty(&doc)
            .context("re-serializing ro-crate-metadata.json with the DR-11 entity")?;
        std::fs::write(&descriptor, serialized)
            .with_context(|| format!("writing {}", descriptor.display()))?;
    }
    Ok(changed)
}

/// Drop `@graph` entries from `dst/ro-crate-metadata.json` whose `@id` is a
/// package-relative path that does not exist on disk under `dst`.
///
/// Only entries whose `@id` looks like a package-relative file/dir path are
/// candidates: fragment ids (`#…`), absolute IRIs (`http://…` / `https://…`),
/// and the root self-reference (`./`) are always retained. A directory id
/// (trailing `/`) is kept iff the directory exists. Returns the number of
/// entries removed. No-op (`Ok(0)`) when the descriptor is missing or
/// unparseable.
fn prune_rocrate_dangling(dst: &Path) -> Result<usize> {
    use serde_json::Value;

    let descriptor = dst.join("ro-crate-metadata.json");
    let Ok(bytes) = std::fs::read(&descriptor) else {
        return Ok(0);
    };
    let Ok(mut doc) = serde_json::from_slice::<Value>(&bytes) else {
        return Ok(0);
    };
    let Some(graph) = doc.get_mut("@graph").and_then(Value::as_array_mut) else {
        return Ok(0);
    };

    // A package-relative `@id` dangles iff its target is absent on disk under
    // `dst`; the crate root (`./`), `#`-fragment entities, and absolute IRIs
    // are never path-backed and are always kept.
    let is_dangling = |id: &str| -> bool {
        if id == "./"
            || id.starts_with('#')
            || id.starts_with("http://")
            || id.starts_with("https://")
        {
            return false;
        }
        // A directory id carries a trailing `/`; `Path::exists` handles both.
        !dst.join(id.trim_end_matches('/')).exists()
    };

    // First pass: collect the ids that will be pruned, so the second pass can
    // also scrub references TO them. A dropped file's `@id` left inside another
    // entry's `hasPart`/`object`/`result` array dangles, and consumers (e.g.
    // runcrate) choke on the unresolvable reference.
    let mut pruned: std::collections::HashSet<String> = graph
        .iter()
        .filter_map(|e| e.get("@id").and_then(Value::as_str))
        .filter(|id| is_dangling(id))
        .map(String::from)
        .collect();

    // Also remove the `#action/<path>` CreateAction node keyed off each pruned
    // path (the emitter's per-output action-id convention) — e.g. the
    // de_table.tsv producer action once a duplicate table is dropped — so no
    // resultless action lingers. A derived id that matches no node is a no-op.
    let derived_action_ids: Vec<String> = pruned.iter().map(|p| format!("#action/{p}")).collect();
    pruned.extend(derived_action_ids);

    let before = graph.len();
    graph.retain(|entry| {
        entry
            .get("@id")
            .and_then(Value::as_str)
            .is_none_or(|id| !pruned.contains(id))
    });
    let removed = before - graph.len();

    // Second pass: scrub references to pruned ids from the surviving entries so
    // no `hasPart`/`object`/`result`/… reference points at a dropped node.
    if !pruned.is_empty() {
        let is_pruned_ref = |v: &Value| -> bool {
            v.get("@id")
                .and_then(Value::as_str)
                .is_some_and(|id| pruned.contains(id))
        };
        for entry in graph.iter_mut() {
            let Some(obj) = entry.as_object_mut() else {
                continue;
            };
            let keys: Vec<String> = obj.keys().cloned().collect();
            for k in keys {
                match obj.get_mut(&k) {
                    Some(Value::Array(arr)) => arr.retain(|it| !is_pruned_ref(it)),
                    Some(v) if is_pruned_ref(v) => {
                        obj.remove(&k);
                    }
                    _ => {}
                }
            }
        }
    }

    if removed > 0 {
        let serialized = serde_json::to_vec_pretty(&doc)
            .context("re-serializing pruned ro-crate-metadata.json")?;
        std::fs::write(&descriptor, serialized)
            .with_context(|| format!("writing pruned {}", descriptor.display()))?;
    }
    Ok(removed)
}

/// Mark rows in every kept per-task `runtime/outputs/<task>/reads.jsonl`
/// manifest (the agent's raw observed-read record, appended as it opens
/// declared input files — see `crates/harness/src/observed_reads.rs`) whose
/// `path` no longer resolves to a file under `dst` once tier/profile drops
/// have run. Uses the same existence predicate as [`prune_rocrate_dangling`]
/// (`!dst.join(rel).exists()`).
///
/// A dangling row is never deleted — that would erase the provenance fact
/// that the read occurred — but is annotated `"available": false` and
/// `"dropped_at_export": true`, honestly declaring the payload absent while
/// preserving the read record itself. Only rows that actually dangle are
/// rewritten; a malformed line, a non-object row, or a row with no `path`
/// field is left byte-for-byte untouched, and a file with nothing to mark is
/// not rewritten at all. Object key order on a rewritten row is always
/// alphabetical (no `preserve_order` feature on `serde_json` in this
/// workspace), so the rewrite is stable across runs. Per-task validation
/// record files (`validation*.json` / `result.json`) are deliberately left
/// untouched: unlike the manifest's fixed `path`/`declared_port` shape, their
/// only well-known path-like field is `StructuredClaim.evidence` (in
/// `result.json`'s `claims[]`), which is resolved package-wide by bare
/// basename and carries `::pointer` self-reference semantics the
/// claim-verifier itself already interprets — rewriting it here without
/// reproducing that resolution risks turning a correct citation into a false
/// "dropped" mark. Returns the number of rows marked.
fn mark_dangling_reads_manifest_rows(dst: &Path) -> Result<usize> {
    use serde_json::Value;

    let outputs = dst.join("runtime").join("outputs");
    if !outputs.is_dir() {
        return Ok(0);
    }
    let Ok(entries) = std::fs::read_dir(&outputs) else {
        return Ok(0);
    };
    let mut task_dirs: Vec<PathBuf> = entries.flatten().map(|e| e.path()).filter(|p| p.is_dir()).collect();
    task_dirs.sort();

    let mut marked = 0usize;
    for task_dir in task_dirs {
        let manifest = task_dir.join("reads.jsonl");
        let Ok(body) = std::fs::read_to_string(&manifest) else {
            continue;
        };
        let mut changed = false;
        let mut rewritten_lines: Vec<String> = Vec::with_capacity(body.lines().count());
        for line in body.lines() {
            let Ok(mut row) = serde_json::from_str::<Value>(line) else {
                rewritten_lines.push(line.to_string());
                continue;
            };
            let Some(obj) = row.as_object_mut() else {
                rewritten_lines.push(line.to_string());
                continue;
            };
            let dangling = obj
                .get("path")
                .and_then(Value::as_str)
                .is_some_and(|rel| !dst.join(rel).exists());
            if !dangling {
                rewritten_lines.push(line.to_string());
                continue;
            }
            obj.insert("available".to_string(), Value::Bool(false));
            obj.insert("dropped_at_export".to_string(), Value::Bool(true));
            changed = true;
            marked += 1;
            rewritten_lines.push(serde_json::to_string(&row).unwrap_or_else(|_| line.to_string()));
        }
        if changed {
            let mut out = rewritten_lines.join("\n");
            if body.ends_with('\n') {
                out.push('\n');
            }
            std::fs::write(&manifest, out).with_context(|| format!("rewriting {}", manifest.display()))?;
        }
    }
    Ok(marked)
}

/// Write every file under `src_dir` into the zip writer `out` at its
/// `src_dir`-relative path, Deflated. Directories are emitted as explicit
/// entries (trailing `/`) so empty dirs survive the round-trip; entries are
/// written in sorted order for determinism.
pub fn zip_dir(src_dir: &Path, out: &mut (impl std::io::Write + std::io::Seek)) -> Result<()> {
    use std::io::Read;
    use zip::write::SimpleFileOptions;

    let mut writer = zip::ZipWriter::new(out);
    let options = SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);

    for entry in walkdir::WalkDir::new(src_dir).sort_by_file_name() {
        let entry = entry.with_context(|| format!("walking {}", src_dir.display()))?;
        let abs = entry.path();
        let rel = abs
            .strip_prefix(src_dir)
            .with_context(|| format!("stripping {} from {}", src_dir.display(), abs.display()))?;
        if rel.as_os_str().is_empty() {
            // The root dir itself — no entry.
            continue;
        }
        let rel_str = rel.to_string_lossy().replace('\\', "/");

        if entry.file_type().is_dir() {
            writer
                .add_directory(format!("{rel_str}/"), options)
                .with_context(|| format!("adding zip directory {rel_str}"))?;
        } else if entry.file_type().is_file() {
            writer
                .start_file(&rel_str, options)
                .with_context(|| format!("starting zip entry {rel_str}"))?;
            let mut f = std::fs::File::open(abs)
                .with_context(|| format!("opening {}", abs.display()))?;
            let mut buf = Vec::new();
            f.read_to_end(&mut buf)
                .with_context(|| format!("reading {}", abs.display()))?;
            std::io::Write::write_all(&mut writer, &buf)
                .with_context(|| format!("writing zip entry {rel_str}"))?;
        }
    }

    writer.finish().context("finalizing zip archive")?;
    Ok(())
}

